import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const handlers = new Map();
const choice = (name, checked) => ({ dataset: { bkMethod: name }, checked, addEventListener(type, callback) { handlers.set(name, callback); } });
const choices = [choice('quick', true), choice('kva', false), choice('search', false)];
const panels = choices.map(c => ({ dataset: { bkPanel: c.dataset.bkMethod }, hidden: false, value: 'already entered' }));
const document = { querySelectorAll(selector) { return selector === '[data-bk-method]' ? choices : panels; }, getElementById() { return null; } };
vm.runInNewContext(readFileSync(new URL('../public/intern/calculation-workspace.js', import.meta.url), 'utf8'), { document });
assert.deepEqual(panels.map(p => p.hidden), [false, true, true]);
choices[1].checked = true; handlers.get('kva')();
assert.deepEqual(panels.map(p => p.hidden), [false, false, true]);
choices[0].checked = false; handlers.get('quick')();
assert.deepEqual(panels.map(p => p.hidden), [true, false, true]);
choices[1].checked = false; choices[2].checked = true; handlers.get('search')();
assert.deepEqual(panels.map(p => p.hidden), [true, true, false]);
assert(panels.every(p => p.value === 'already entered'), 'Switching input methods must retain the inputs.');
const page = readFileSync(new URL('../src/pages/intern/kalkulation/index.astro', import.meta.url), 'utf8');
assert.equal((page.match(/action=list/g) || []).length, 1, 'Only one history loader is allowed.');
console.log('Calculation workspace: individual and combined methods, input retention and one history loader verified.');
